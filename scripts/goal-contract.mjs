/*
 * RespawnPack · scripts/goal-contract.mjs — the durable goal contract at docs/goal.md, parsed and validated.
 *
 * The schema lives at schemas/goal.schema.json. The runtime active-goal pointer lives at
 * .respawnpack/runtime/contract.json (gitignored). This module is the boundary between them: it reads the
 * markdown, parses the YAML-ish frontmatter, validates the shape, and exposes read/write helpers for the
 * bridge to consume.
 *
 * ⛔ WHY A LINE-BASED FRONTMATTER PARSER, NOT A LIBRARY. The skill suite already has a hand-rolled
 * line-based parser (skills/skills.test.mjs), and adding ajv/yaml as a dependency would force the package
 * to grow one for a 200-line use site. The shape is fixed and small: 9 top-level fields, 3 of them lists.
 * A 60-line parser covers it and tests can pin the exact failure mode line-by-line.
 *
 * ⛔ SCHEMA COVERAGE IS DELIBERATELY A SUBSET. The schema at schemas/goal.schema.json describes the
 * upstream durable JSON goal doc (the kernel's writeGoalDoc() output). The markdown frontmatter in this
 * package is a SUPERSET: it adds `status` (pending|in_progress|done) so the operator can mark a goal
 * completed, and `markdownBody` (string) so the goal can carry prose context. Validation here enforces
 * the schema's load-bearing fields (id, goal, completion[], constraints[], authority[], forbidden[],
 * externalBlockers[], contextStages) plus the new `status` enum. Field-by-field type checks only —
 * deep semantic checks (e.g. gate-known-to-be-defined) are NOT done here; the schema's `kind`/`gate`
 * completion objects are kept as opaque strings so a goal can name a future gate without this parser
 * growing a gate registry.
 *
 * ⛔ RUNTIME CONTRACT IS GITIGNORED. .respawnpack/runtime/contract.json is a transient pointer: which goal
 * is active, the current atomic task, when the goal mode started, the cycle count. It is generated by
 * this module on first goal-mode entry and updated by the bridge on each checkpoint. It is NEVER read by
 * the goal-md validation path — that path validates the durable doc only.
 */

import fs from 'node:fs';
import path from 'node:path';

/** The path inside the project that holds the durable goal doc. Operator-tracked. */
export const DEFAULT_GOAL_MD_PATH = 'docs/goal.md';

/** The path inside the project that holds the runtime active-goal pointer. Gitignored. */
export const RUNTIME_CONTRACT_PATH = '.respawnpack/runtime/contract.json';

/** The schema version this parser enforces on the goal frontmatter. Matches schemas/goal.schema.json. */
export const GOAL_SCHEMA_VERSION = '1.0.0';

/** The runtime contract schema version. Separate from the goal schema because they evolve independently. */
export const CONTRACT_SCHEMA_VERSION = '1.0.0';

/** Allowed values for the `status` field on a goal. Pending → in_progress → done. */
const ALLOWED_STATUS = new Set(['pending', 'in_progress', 'done']);

/** Lock file for serializing concurrent writes to the runtime contract. Lives next to contract.json so
 *  it stays out of git (the parent dir is gitignored via .respawnpack/). The directory-create form is
 *  portable (POSIX mkdir returns EEXIST; Windows can return EPERM/EACCES during a delete-pending window
 *  — see hooks/_index-lease.js for the same content-codeset). mkdirSync IS atomic on both, so two
 *  concurrent writers cannot both succeed.
 *
 *  Why this is duplicated rather than imported from hooks/_index-lease.js:
 *    - _index-lease.js is CommonJS, this file is ESM; cross-tree CJS↔ESM interop would force a wrapper
 *    - the lock contract is 60 lines, the pattern is small, and the divergence is bounded (both
 *      implementations share the same content-code set, the same Atomics.wait yield, and the same
 *      fail-closed deadline). A reviewer's job is to keep the two in step; a future refactor that
 *      unifies them belongs in its own brick.
 */
const CONTRACT_LOCK_PATH = path.join('.respawnpack', '.contract.lock');
const LOCK_CONTENTION_CODES = new Set(['EEXIST', 'EPERM', 'EACCES', 'EBUSY']);
const LOCK_DEADLINE_MS = 4000;
const LOCK_PAUSE_MS = 3;

const syncPause = () => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, LOCK_PAUSE_MS);

/**
 * Run `fn` under an exclusive writer lock on the contract, or throw if exclusivity cannot be established
 * within LOCK_DEADLINE_MS. Returns whatever `fn` returns. NEVER runs `fn` unlocked.
 *
 * The lock is at `<projectDir>/.respawnpack/.contract.lock` — a directory, because mkdirSync is
 * atomic on POSIX and Windows, and the sibling contract.json is also a path whose parent must exist
 * for the writer's own mkdirSync (which we still call defensively inside writeRuntimeContract).
 */
function withContractLock(projectDir, fn) {
  const lockPath = path.join(projectDir, CONTRACT_LOCK_PATH);
  try { fs.mkdirSync(path.dirname(lockPath), { recursive: true }); }
  catch { /* parent dir already exists — the common case */ }
  const deadline = Date.now() + LOCK_DEADLINE_MS;
  for (;;) {
    try { fs.mkdirSync(lockPath); break; }
    catch (e) {
      const code = (e && e.code) || 'UNKNOWN';
      if (!LOCK_CONTENTION_CODES.has(code)) {
        throw new Error(`cannot create the contract lock at ${lockPath}: ${code === 'UNKNOWN' ? (e && e.message) : code}`);
      }
      if (Date.now() > deadline) {
        throw new Error(`timed out contending for the contract lock at ${lockPath} (last error ${code}) — another writer is active`);
      }
      syncPause();
    }
  }
  try { return fn(); }
  finally { try { fs.rmdirSync(lockPath); } catch { /* already gone — fine */ } }
}

// ---------------------------------------------------------------------------------------------
// frontmatter parser — line-based, mirrors skills/skills.test.mjs#parseFrontmatter.
// Returns {frontmatter: object, body: string, errors: string[]}.
// ---------------------------------------------------------------------------------------------

/**
 * Parse a markdown file's frontmatter. Splits on the FIRST `---` line followed by another `---` line;
 * anything between them is the frontmatter (one `key: value` or `key:` per line, list items as
 * `- value`). Anything after the closing `---` is the body. Nested objects (contextStages,
 * completion-kind gates) are serialized as inline JSON inside a string value — keeps the parser
 * line-based.
 *
 * @param {string} text — the file's full contents
 * @returns {{frontmatter: object, body: string, errors: string[]}}
 */
export function parseFrontmatter(text) {
  const errors = [];
  const lines = String(text || '').replace(/\r\n/g, '\n').split('\n');
  if (lines[0] !== '---') { errors.push('frontmatter open delimiter `---` not on line 1'); return { frontmatter: {}, body: text || '', errors }; }

  // Find the closing delimiter — the next line that is exactly `---`. Allow up to 200 lines of frontmatter
  // (a goal doc with a long prose-style completion list rarely exceeds 60 lines; 200 is a soft cap that
  // catches accidental "open without close" before it becomes a parse-time crash).
  let closeIdx = -1;
  for (let i = 1; i < lines.length && i < 200; i++) {
    if (lines[i] === '---') { closeIdx = i; break; }
  }
  if (closeIdx === -1) { errors.push('frontmatter close delimiter `---` not found within first 200 lines'); return { frontmatter: {}, body: '', errors }; }

  const fmLines = lines.slice(1, closeIdx);
  const body = lines.slice(closeIdx + 1).join('\n').replace(/^\n/, '');

  // Parse the frontmatter. Each line is one of:
  //   `key: value` — value is a string, possibly quoted ("...") or inline JSON ({...}, [...])
  //   `key:`       — value is the next non-blank, non-`- `-prefixed line treated as a single string
  //                  (used for multi-line prose values; kept simple on purpose)
  //   `- value`    — when previous key had no inline value, appends to that key's list
  const fm = {};
  let listKey = null;
  for (let i = 0; i < fmLines.length; i++) {
    const raw = fmLines[i];
    const trimmed = raw.trim();
    if (trimmed === '') continue;
    if (trimmed.startsWith('#')) continue; // comment

    // A list item continues the most recent key.
    if (trimmed.startsWith('- ') && listKey) {
      fm[listKey] = fm[listKey] || [];
      fm[listKey].push(tryParseInlineJSON(stripQuotes(trimmed.slice(2).trim())));
      continue;
    }

    const m = /^([A-Za-z_][A-Za-z0-9_-]*)\s*:\s*(.*)$/.exec(trimmed);
    if (!m) { errors.push(`line ${i + 2}: cannot parse "${trimmed}"`); continue; }
    const [, key, valueRaw] = m;
    const value = stripQuotes(valueRaw.trim());
    if (value === '') {
      // list-followed-by-blank-then-item pattern; the key starts a list
      fm[key] = fm[key] || [];
      listKey = key;
    } else {
      fm[key] = tryParseInlineJSON(value);
      listKey = null;
    }
  }

  return { frontmatter: fm, body, errors };
}

/** Strip surrounding double-quotes; tolerate single quotes too. */
function stripQuotes(s) {
  if (s.length >= 2 && ((s.startsWith('"') && s.endsWith('"')) || (s.startsWith("'") && s.endsWith("'")))) return s.slice(1, -1);
  return s;
}

/** Try to parse the value as JSON (object/array/number/bool). Strings stay strings.
 * YAML-ish shorthand is tolerated for flat objects (`{ key: value, key2: "v2" }`) so the operator can
 * write `contextStages: { checkpoint: 60, closeout: 75, handoff: 85 }` without quoting every key.
 * Single-quoted strings are also tolerated (`{ kind: 'gate-complete' }`) — they normalize to double-
 * quoted before the JSON.parse. Nested unquoted-key structure is intentionally NOT supported; deep
 * structure belongs in the JSON it actually is. */
function tryParseInlineJSON(s) {
  if (!(s.startsWith('{') || s.startsWith('[') || s === 'true' || s === 'false' || s === 'null' || /^-?\d/.test(s))) return s;
  // Try strict JSON first.
  try { return JSON.parse(s); } catch { /* fall through to YAML-ish normalization */ }
  // Quote unquoted keys adjacent to `{`, `,`, or `[` at depth zero.
  const quotedKeys = s.replace(/([{,[]\s*)([A-Za-z_][A-Za-z0-9_-]*)\s*:/g, '$1"$2":');
  // Convert single-quoted strings to double-quoted. Tolerant: skip escaped quotes inside.
  const normalized = quotedKeys.replace(/'((?:\\'|[^'])*)'/g, (_, inner) => `"${inner.replace(/"/g, '\\"')}"`);
  try { return JSON.parse(normalized); } catch { /* fall through */ }
  return s;
}

