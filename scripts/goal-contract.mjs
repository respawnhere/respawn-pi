/**
 * Validate the parsed frontmatter against the goal schema (subset). Returns `{ok, errors[]}`.
 * `errors[]` items are strings intended for log output, not thrown — callers decide the severity.
 */
export function validateGoal(frontmatter) {
  const errors = [];
  const fm = frontmatter || {};

  if (fm.schemaVersion !== GOAL_SCHEMA_VERSION) errors.push(`schemaVersion must be "${GOAL_SCHEMA_VERSION}", got ${JSON.stringify(fm.schemaVersion)}`);

  for (const required of ['goalId', 'goal', 'completion', 'constraints', 'contextStages']) {
    if (fm[required] === undefined || fm[required] === null) errors.push(`required field "${required}" is missing`);
  }

  if (typeof fm.goalId !== 'string' || !/^G-[A-Za-z0-9_-]+$/.test(fm.goalId)) errors.push(`goalId must match /^G-[A-Za-z0-9_-]+$/, got ${JSON.stringify(fm.goalId)}`);
  if (typeof fm.goal !== 'string' || fm.goal.length === 0) errors.push(`goal must be a non-empty string, got ${JSON.stringify(fm.goal)}`);

  if (!Array.isArray(fm.completion)) errors.push(`completion must be an array, got ${typeof fm.completion}`);
  else if (fm.completion.length === 0) errors.push('completion must be a non-empty array — a goal without completion criteria is not a goal');

  if (fm.constraints !== undefined && !Array.isArray(fm.constraints)) errors.push(`constraints must be an array when present, got ${typeof fm.constraints}`);
  if (fm.authority !== undefined && !Array.isArray(fm.authority)) errors.push(`authority must be an array when present, got ${typeof fm.authority}`);
  if (fm.forbidden !== undefined && !Array.isArray(fm.forbidden)) errors.push(`forbidden must be an array when present, got ${typeof fm.forbidden}`);
  if (fm.externalBlockers !== undefined && !Array.isArray(fm.externalBlockers)) errors.push(`externalBlockers must be an array when present, got ${typeof fm.externalBlockers}`);

  if (fm.contextStages !== undefined) {
    const stages = fm.contextStages;
    if (typeof stages !== 'object' || Array.isArray(stages) || stages === null) {
      errors.push('contextStages must be an object, got ' + typeof stages);
    } else {
      for (const k of ['checkpoint', 'closeout', 'handoff']) {
        const v = stages[k];
        if (typeof v !== 'number' || !Number.isFinite(v) || v <= 0 || v > 100) errors.push(`contextStages.${k} must be a number in (0, 100], got ${JSON.stringify(v)}`);
      }
      if (typeof stages.checkpoint === 'number' && typeof stages.closeout === 'number' && stages.checkpoint >= stages.closeout) errors.push(`contextStages.checkpoint (${stages.checkpoint}) must be < contextStages.closeout (${stages.closeout})`);
      if (typeof stages.closeout === 'number' && typeof stages.handoff === 'number' && stages.closeout >= stages.handoff) errors.push(`contextStages.closeout (${stages.closeout}) must be < contextStages.handoff (${stages.handoff})`);
    }
  }

  if (fm.status !== undefined && !ALLOWED_STATUS.has(fm.status)) errors.push(`status must be one of ${[...ALLOWED_STATUS].join('|')}, got ${JSON.stringify(fm.status)}`);

  if (fm.createdAt !== undefined) {
    const t = Date.parse(fm.createdAt);
    if (!Number.isFinite(t)) errors.push(`createdAt must be an ISO 8601 timestamp, got ${JSON.stringify(fm.createdAt)}`);
  }
  if (fm.completedAt !== undefined && fm.status !== 'done') errors.push(`completedAt is only valid when status is "done"`);

  return { ok: errors.length === 0, errors };
}

// ---------------------------------------------------------------------------------------------
// file readers and writers — small, sync, atomic where it matters
// ---------------------------------------------------------------------------------------------

/**
 * Read `docs/goal.md` (or an override path) and return the parsed + validated goal.
 * Returns `{ok:true, goal, body, source}` on success, `{ok:false, reason}` when missing/invalid.
 * `reason` is a human-readable string for log output.
 */
export function readGoalMd(projectDir, relativePath = DEFAULT_GOAL_MD_PATH) {
  const abs = path.join(projectDir, relativePath);
  if (!fs.existsSync(abs)) return { ok: false, reason: `goal doc not found at ${relativePath}`, code: 'MISSING', goal: null, body: '' };
  let text;
  try { text = fs.readFileSync(abs, 'utf8'); } catch (e) { return { ok: false, reason: `could not read ${relativePath}: ${e.message}`, code: 'READ_ERROR', goal: null, body: '' }; }
  const parsed = parseFrontmatter(text);
  if (parsed.errors.length) return { ok: false, reason: `frontmatter parse failed: ${parsed.errors.join('; ')}`, code: 'PARSE_ERROR', goal: null, body: '' };
  const v = validateGoal(parsed.frontmatter);
  if (!v.ok) return { ok: false, reason: `goal validation failed: ${v.errors.join('; ')}`, code: 'VALIDATION_ERROR', goal: null, body: '' };
  return { ok: true, goal: parsed.frontmatter, body: parsed.body, source: relativePath };
}

/**
 * Read `.respawnpack/runtime/contract.json`. Returns `null` when absent (no goal mode active yet),
 * or `{ok, contract, reason}` otherwise. A malformed contract is an error: do not silently fall back,
 * because the goal mode is supposed to be deterministic and a corrupted pointer is a real signal.
 */
export function readRuntimeContract(projectDir) {
  const abs = path.join(projectDir, RUNTIME_CONTRACT_PATH);
  if (!fs.existsSync(abs)) return { ok: true, contract: null, reason: 'no active goal mode (contract.json absent)' };
  let doc;
  try { doc = JSON.parse(fs.readFileSync(abs, 'utf8')); } catch (e) { return { ok: false, contract: null, reason: `contract.json is not valid JSON: ${e.message}`, code: 'PARSE_ERROR' }; }
  if (typeof doc !== 'object' || doc === null || Array.isArray(doc)) return { ok: false, contract: null, reason: 'contract.json root must be an object', code: 'SHAPE_ERROR' };
  if (doc.schemaVersion !== CONTRACT_SCHEMA_VERSION) return { ok: false, contract: null, reason: `contract.json schemaVersion must be "${CONTRACT_SCHEMA_VERSION}", got ${JSON.stringify(doc.schemaVersion)}`, code: 'SCHEMA_ERROR' };
  if (doc.mode !== 'goal') return { ok: false, contract: null, reason: `contract.json mode must be "goal", got ${JSON.stringify(doc.mode)}`, code: 'MODE_ERROR' };
  return { ok: true, contract: doc, reason: 'ok' };
}

/**
 * Write the runtime contract atomically (write to a tmp file in the same dir, fsync, rename).
 * Caller passes the full document; this function does NOT merge — it overwrites. The merge lives in the
 * caller (the bridge) so the contract's invariants stay in one place.
 */
export function writeRuntimeContract(projectDir, contract) {
  const abs = path.join(projectDir, RUNTIME_CONTRACT_PATH);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  const tmp = abs + '.tmp';
  fs.writeFileSync(tmp, JSON.stringify(contract, null, 2) + '\n');
  fs.renameSync(tmp, abs);
  return { ok: true, path: abs };
}

/**
 * Initialise the runtime contract from a goal doc + start time. Pure: caller passes the values, this
 * function assembles the document. Designed so the bridge can call it at the first session_start where
 * goal mode begins (no contract.json present yet) without taking on shape concerns.
 */
export function initRuntimeContract({ goalId, goalText, atomicTask, startedAt }) {
  return {
    schemaVersion: CONTRACT_SCHEMA_VERSION,
    mode: 'goal',
    activeGoalId: goalId,
    goal: goalText,
    currentAtomicTask: atomicTask || null,
    startedAt: startedAt || new Date().toISOString(),
    cycleCount: 0,
    lastProgressAt: null,
    lastCheckpointAt: null,
    handoffs: [],
  };
}

/**
 * Activate a goal: read docs/goal.md, validate, derive the first atomic task from the first unmet
 * completion item, refuse if a contract.json already names a DIFFERENT active goal (an unclosed goal
 * blocks a new one — operator must `/run-goal close` first). Atomic-write the new contract. Returns
 * `{ok, contract, thresholds, goal}` or `{ok:false, reason}`. This is the entry point the `/run-goal`
 * skill and any future tooling share.
 */
export function activateGoal(projectDir, opts = {}) {
  const durable = readGoalMd(projectDir);
  if (!durable.ok) return { ok: false, reason: `goal.md: ${durable.reason}` };
  const goalId = durable.goal.goalId;
  const existing = readRuntimeContract(projectDir);
  if (existing.ok && existing.contract && existing.contract.activeGoalId && existing.contract.activeGoalId !== goalId) {
    return { ok: false, reason: `an active goal is already running: ${existing.contract.activeGoalId} (${existing.contract.goal || '(no text)'}). Close it first (\`/run-goal close\` or edit .respawnpack/runtime/contract.json to remove activeGoalId).` };
  }
  const t = thresholdsForGoal(durable.goal);
  if (!t.ok) return { ok: false, reason: t.reason };
  const atomicTask = opts.atomicTask || nextUnmetCompletion(durable.goal);
  // Re-activate for the SAME goalId preserves cycleCount + handoff history (the operator is
  // refreshing the contract, not starting a fresh run). A different goalId would have been
  // refused above. We still reset startedAt to "now" if the previous contract was closed.
  const preserved = (existing.ok && existing.contract && existing.contract.activeGoalId === goalId) ? existing.contract : null;
  const base = initRuntimeContract({ goalId, goalText: durable.goal.goal, atomicTask });
  const contract = preserved
    ? { ...base, cycleCount: preserved.cycleCount || 0, handoffs: preserved.handoffs || [], sessions: preserved.sessions || [], startedAt: preserved.startedAt || base.startedAt }
    : base;
  const w = writeRuntimeContract(projectDir, contract);
  if (!w.ok) return { ok: false, reason: `contract write failed: ${w.reason}` };
  return { ok: true, contract, thresholds: t.thresholds, goal: durable.goal };
}

/**
 * Close a goal: if a contract.json exists AND its activeGoalId matches the given (or any, when
 * `goalId` is null), null out activeGoalId and stamp closedAt. The contract is preserved for
 * audit (the bridge still reads/writes it; the rollover extension uses activeGoalId presence as
 * the on/off switch). Returns `{ok, contract}` or `{ok:false, reason}`.
 */
export function closeGoal(projectDir, goalId = null) {
  return withContractLock(projectDir, () => {
    const existing = readRuntimeContract(projectDir);
    if (!existing.ok || !existing.contract) return { ok: false, reason: 'no active contract to close' };
    if (existing.contract.activeGoalId == null) return { ok: true, contract: existing.contract, reason: 'already closed' };
    if (goalId != null && existing.contract.activeGoalId !== goalId) {
      return { ok: false, reason: `active goal is ${existing.contract.activeGoalId}, not ${goalId}` };
    }
    const next = { ...existing.contract, activeGoalId: null, closedAt: new Date().toISOString() };
    const w = writeRuntimeContract(projectDir, next);
    if (!w.ok) return { ok: false, reason: `contract write failed: ${w.reason}` };
    return { ok: true, contract: next };
  });
}

/**
 * Increment the cycle counter and stamp `lastProgressAt`. Called by `stop-savepoint` when the
 * session ends in goal mode, and by the rollover extension when a closeout fires. Idempotent on
 * a missing contract (no-op with `ok:false, reason:'no contract'`).
 *
 * ⛔ CONCURRENT-WRITE SAFETY. The read-modify-write cycle is serialized by an exclusive writer lock
 * (withContractLock, see top of file). POSIX rename(2) inside writeRuntimeContract is what protects
 * against TORN writes (a half-flushed file seen by a reader); it does NOT protect against LOST
 * UPDATES — two concurrent bumps both reading cycleCount=0 and both writing cycleCount=1 is a race
 * the rename cannot see. The lock is what stops it. A 4-second deadline is enforced; on timeout the
 * call throws so the caller can decide whether to log + skip (the rollover extension's pattern) or
 * surface the error.
 */
export function bumpCycleCount(projectDir, sessionId) {
  return withContractLock(projectDir, () => {
    const existing = readRuntimeContract(projectDir);
    if (!existing.ok || !existing.contract) return { ok: false, reason: 'no contract' };
    const next = {
      ...existing.contract,
      cycleCount: (existing.contract.cycleCount || 0) + 1,
      lastProgressAt: new Date().toISOString(),
      sessions: [...(existing.contract.sessions || []), { sessionId: sessionId || null, at: new Date().toISOString() }].slice(-32),
    };
    const w = writeRuntimeContract(projectDir, next);
    if (!w.ok) return { ok: false, reason: `contract write failed: ${w.reason}` };
    return { ok: true, contract: next };
  });
}

/**
 * First unmet completion item from a goal's `completion[]`. Pure data — the operator marks items
 * done by removing them from the list or moving them to a `done:` block; this function returns the
 * first string in `completion[]` that is NOT preceded by `- done:`. Returns `null` if every item
 * is met (the goal is complete and the operator should `/run-goal close`).
 */
export function nextUnmetCompletion(goal) {
  if (!goal || !Array.isArray(goal.completion)) return null;
  for (const item of goal.completion) {
    if (item == null) continue;
    if (typeof item === 'string') return item;
    if (typeof item === 'object' && item.kind === 'gate-complete') return `gate-complete: ${item.gate}`;
    if (typeof item === 'object' && item.text) return item.text;
  }
  return null;
}

/**
 * Derive the threshold config that `core/policy/thresholds.js` accepts, from a goal's `contextStages`.
 * Returns `{ok, thresholds}` or `{ok:false, reason}` if contextStages is missing or malformed.
 * The three thresholds the policy knows are `advisory`, `checkpoint`, `final`. The goal schema uses
 * `checkpoint`, `closeout`, `handoff`. The mapping is direct: advisory←checkpoint, checkpoint←closeout,
 * final←handoff. The names diverge because the policy thresholds are reused across goals/skills and
 * predate the goal schema; the mapping is the documented contract.
 */
export function thresholdsForGoal(goal) {
  const stages = goal && goal.contextStages;
  if (!stages || typeof stages !== 'object') return { ok: false, reason: 'goal has no contextStages' };
  const advisory = stages.checkpoint;
  const checkpoint = stages.closeout;
  const final = stages.handoff;
  for (const [name, v] of Object.entries({ advisory, checkpoint, final })) {
    const key = name === 'advisory' ? 'checkpoint' : name === 'checkpoint' ? 'closeout' : 'handoff';
    if (typeof v !== 'number' || !Number.isFinite(v) || v <= 0 || v > 100) return { ok: false, reason: `contextStages.${key} must be a number in (0, 100], got ${JSON.stringify(v)}` };
  }
  if (!(advisory < checkpoint && checkpoint < final)) {
    return { ok: false, reason: `thresholds must ascend: advisory (${advisory}) < checkpoint (${checkpoint}) < final (${final})` };
  }
  return { ok: true, thresholds: { advisory, checkpoint, final } };
}

// ---- CLI --------------------------------------------------------------------------------------------
// Small, hand-rolled CLI so the operator can `node scripts/goal-contract.mjs <cmd>` directly without
// the skill body needing to embed node -e one-liners. The CLI is a thin wrapper around the public
// functions above; it never reaches into private helpers. Use the module's exports for richer flows.

if (process.argv[1] && (import.meta.url === `file://${process.argv[1]}` || import.meta.url.endsWith(process.argv[1]))) {
  const cmd = process.argv[2];
  const flag = process.argv[3];
  const projectDir = process.cwd();
  if (cmd === 'activate') {
    const r = activateGoal(projectDir);
    if (!r.ok) { console.error(`activate failed: ${r.reason}`); process.exit(1); }
    console.log(JSON.stringify({ ok: true, activeGoalId: r.contract.activeGoalId, atomicTask: r.contract.currentAtomicTask, thresholds: r.thresholds }, null, 2));
  } else if (cmd === 'close') {
    const r = closeGoal(projectDir, flag && flag !== '--all' ? flag : null);
    if (!r.ok) { console.error(`close failed: ${r.reason}`); process.exit(1); }
    console.log(JSON.stringify({ ok: true, closedAt: r.contract.closedAt || null }, null, 2));
  } else if (cmd === 'status') {
    const c = readRuntimeContract(projectDir);
    const g = readGoalMd(projectDir);
    console.log(JSON.stringify({ contract: c.contract || null, contractReason: c.ok ? null : c.reason, goal: g.ok ? { goalId: g.goal.goalId, status: g.goal.status, completion: g.goal.completion, contextStages: g.goal.contextStages } : null, goalReason: g.ok ? null : g.reason }, null, 2));
  } else if (cmd === 'bump') {
    const r = bumpCycleCount(projectDir, flag || null);
    if (!r.ok) { console.error(`bump failed: ${r.reason}`); process.exit(1); }
    console.log(JSON.stringify({ ok: true, cycleCount: r.contract.cycleCount }, null, 2));
  } else {
    console.error('usage: node scripts/goal-contract.mjs <activate|close [goalId]|status|bump [sessionId]>');
    process.exit(2);
  }
}